#!/usr/bin/env node
/**
 * Local release APK builder for mobile-v2.
 * Loads public EXPO_PUBLIC_* values from eas.json (or .env.<profile>),
 * validates them, materializes a gitignored .env for Expo/Metro inlining,
 * then runs Gradle with those vars in the process environment.
 */
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(__dirname, '..');
const androidDir = path.join(appRoot, 'android');

const profile = process.argv[2] ?? 'hosted-beta';
const gradleTask = process.argv[3] ?? 'assembleRelease';
const extraGradleArgs = process.argv.slice(4);

const PUBLIC_KEYS = [
  'EXPO_PUBLIC_APP_ENV',
  'EXPO_PUBLIC_API_BASE_URL',
  'EXPO_PUBLIC_SMART_RETURN_ENABLED',
];

function loadEasProfile(profileName) {
  const easPath = path.join(appRoot, 'eas.json');
  if (!fs.existsSync(easPath)) {
    return null;
  }
  const eas = JSON.parse(fs.readFileSync(easPath, 'utf8'));
  return eas?.build?.[profileName]?.env ?? null;
}

function loadDotEnvFile(filePath) {
  if (!fs.existsSync(filePath)) {
    return;
  }
  const text = fs.readFileSync(filePath, 'utf8');
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) {
      continue;
    }
    const eq = line.indexOf('=');
    if (eq <= 0) {
      continue;
    }
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (process.env[key] === undefined || process.env[key] === '') {
      process.env[key] = value;
    }
  }
}

function applyEnv(envMap) {
  if (!envMap) {
    return;
  }
  for (const [key, value] of Object.entries(envMap)) {
    if (process.env[key] === undefined || process.env[key] === '') {
      process.env[key] = String(value);
    }
  }
}

function writeGitignoredEnvFile() {
  // Expo / babel-preset-expo load `.env` during export:embed. Writing it from the
  // validated profile guarantees inlining even when a Gradle child drops env.
  const lines = [
    '# Generated by scripts/run-android-release.mjs - do not commit (gitignored).',
    `# profile=${profile}`,
  ];
  for (const key of PUBLIC_KEYS) {
    const value = process.env[key];
    if (value !== undefined && value !== '') {
      lines.push(`${key}=${value}`);
    }
  }
  const envPath = path.join(appRoot, '.env');
  fs.writeFileSync(envPath, `${lines.join('\n')}\n`, 'utf8');
  console.log(`[run-android-release] wrote gitignored .env for profile=${profile}`);
}

function invalidateStaleJsBundle() {
  // Gradle does not watch `.env`; delete prior release bundle outputs so
  // createBundleReleaseJsAndAssets cannot stay UP-TO-DATE with stale inlines.
  const bundleRoots = [
    path.join(androidDir, 'app', 'build', 'generated', 'assets', 'react', 'release'),
    path.join(androidDir, 'app', 'build', 'intermediates', 'sourcemaps', 'react', 'release'),
  ];
  for (const root of bundleRoots) {
    if (fs.existsSync(root)) {
      fs.rmSync(root, { recursive: true, force: true });
      console.log(`[run-android-release] cleared ${path.relative(appRoot, root)}`);
    }
  }
}

loadDotEnvFile(path.join(appRoot, `.env.${profile}`));
applyEnv(loadEasProfile(profile));

const validate = spawnSync(
  process.execPath,
  [path.join(__dirname, 'validate-release-env.mjs'), profile],
  { stdio: 'inherit', env: process.env, cwd: appRoot },
);
if (validate.status !== 0) {
  process.exit(validate.status ?? 1);
}

writeGitignoredEnvFile();
if (/assembleRelease|bundleRelease|createBundleRelease/i.test(gradleTask)) {
  invalidateStaleJsBundle();
}

const isWin = process.platform === 'win32';
const gradlew = path.join(androidDir, isWin ? 'gradlew.bat' : 'gradlew');
if (!fs.existsSync(gradlew)) {
  console.error(`[run-android-release] Missing Gradle wrapper at ${gradlew}`);
  process.exit(1);
}

console.log(
  `[run-android-release] profile=${profile} task=${gradleTask} APP_ENV=${process.env.EXPO_PUBLIC_APP_ENV}`,
);

const gradle = spawnSync(gradlew, [gradleTask, ...extraGradleArgs], {
  stdio: 'inherit',
  env: process.env,
  cwd: androidDir,
  shell: isWin,
});

process.exit(gradle.status ?? 1);
